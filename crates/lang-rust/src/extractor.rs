//! [`RustSourceExtractor`] - honest never-dispatched stub (rust-language R-3).
//!
//! `capabilities().extraction` is `false` at this hop, so the isolation
//! engine never dispatches here. `extract` emits a [`GeneratedSourceFile`]
//! whose content is only an ASCII header comment naming the deferral -
//! inventing generated Rust source without the mechanism would fabricate
//! (SM-1's red rule: shipped stubs are compiling neutral returns). The real
//! extractor (valid Rust source from the ORIGINAL item text, syn printing via
//! `proc_macro2::TokenStream`, comment loss recorded honestly) lands at R-8.

use ariadne_lang::{GeneratedSourceFile, SourceExtractor, SymbolBody};
use std::path::PathBuf;

/// The only bytes the stub emits: a header comment naming the deferral.
const DEFERRAL_HEADER: &str =
    "// generated by AriadnesThread: Rust extraction is not wired yet \
     (rust-language R-8 lands the extractor)\n";

/// Never-dispatched extractor stub: emits the deferral header only.
pub struct RustSourceExtractor;

impl SourceExtractor for RustSourceExtractor {
    /// Bodies and deps are deliberately ignored: emitting them would pretend
    /// the extraction mechanism exists. The path stays empty for the same
    /// reason - no target naming before the R-8 mechanism.
    fn extract(
        &self,
        _symbols: &[SymbolBody],
        _namespace: &str,
        _required_deps: &[String],
    ) -> GeneratedSourceFile {
        GeneratedSourceFile {
            path: PathBuf::new(),
            content: DEFERRAL_HEADER.to_string(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn extract_emits_only_the_deferral_header() {
        let generated = RustSourceExtractor.extract(
            &[SymbolBody {
                name: "Greeter".to_string(),
                body: "pub struct Greeter;".to_string(),
            }],
            "crate",
            &["crate::models".to_string()],
        );
        assert!(
            generated.content.starts_with("//") && generated.content == DEFERRAL_HEADER,
            "content is ONLY the ASCII header comment naming the deferral; the \
             passed body/dep must not leak into never-dispatched bytes"
        );
        assert!(
            generated.content.is_ascii(),
            "every authored/generated byte is pure ASCII"
        );
    }
}
