//! [`RustSourceExtractor`] - generated Rust unit text (rust-language R-8).
//!
//! Byte shape: an ASCII header comment naming the generator and its honest
//! limit, a blank separator, the referenced-deps block (one `use <dep>;`
//! line per required dependency, sorted and deduped, rendered verbatim -
//! dependency selection is upstream and this renderer is dumb on purpose,
//! the Scala extractor's D-M23-13 discipline), then each item body followed
//! by exactly one `\n`.
//!
//! The item text is the ORIGINAL written item re-printed from the parsed
//! tree: the `ToTokens` seam (imported below - see the note there) hands
//! the item's `proc_macro2::TokenStream` to `to_string` - valid Rust by
//! construction (the pin tests re-parse every generated byte with `syn`).
//! Honest limit (the D-2 caveat family): `syn` printing normalizes
//! whitespace and DROPS COMMENTS - a body printed from a token stream has
//! nowhere to carry them. The header states the limit on the generated
//! file itself.
//!
//! `namespace` is deliberately clause-free: Rust file reachability is
//! placement in the module tree (`mod` declarations), not a file-level
//! namespace clause, so the default (empty) `unit_namespace` is the honest
//! seam answer and `extract` emits no clause for whatever the engine
//! passes. The path stays empty for the engine to fill (the C++/Scala
//! stance), and [`SourceExtractor::places_generated_units_in_place`] is
//! TRUE: a `generated/` staging dir is outside the module tree and would
//! strand the extracted file invisible (RISK-MODTREE, shape sec. 6).

use ariadne_lang::{GeneratedSourceFile, SourceExtractor, SymbolBody};
use std::path::PathBuf;
// The printing trait rides `syn::__private` (the `#[doc(hidden)] pub` alias
// of syn's export module, re-exporting `quote::ToTokens` under the default
// `printing` feature): `quote` is not a direct dependency of this crate and
// Cargo.toml is outside the R-8 touch-set, while the handoff names the
// mechanism - `proc_macro2::TokenStream` to-string via syn printing.
// Journal D1 records the seam choice and its reason.
use syn::__private::ToTokens;

/// The header every generated unit carries: generator provenance plus the
/// comment-loss limit, stated where a reader of the file will see it.
const GENERATION_HEADER: &str = "// generated by AriadnesThread (rust-language R-8): extracted Rust unit\n\
     // syn-printed content - comments in the written source do not survive\n";

/// Generates the text of newly extracted Rust source files.
pub struct RustSourceExtractor;

impl SourceExtractor for RustSourceExtractor {
    /// Header + `use` block + each body with one trailing `\n`. The
    /// `namespace` argument earns no clause (module-tree placement is the
    /// carrier); the empty `path` is the engine's to fill.
    fn extract(
        &self,
        symbols: &[SymbolBody],
        namespace: &str,
        required_deps: &[String],
    ) -> GeneratedSourceFile {
        let _ = namespace;
        let mut content = String::from(GENERATION_HEADER);
        content.push('\n');
        let use_block = render_use_block(required_deps);
        if !use_block.is_empty() {
            content.push_str(&use_block);
            content.push('\n');
        }
        for symbol in symbols {
            content.push_str(&symbol.body);
            content.push('\n');
        }
        GeneratedSourceFile {
            path: PathBuf::new(),
            content,
        }
    }

    /// The written top-level items `syn` sees, re-printed as valid Rust.
    /// Names absent from the file (including anything only a macro
    /// expansion would create - the D-2 caveat specimen) are simply
    /// omitted; the engine keeps its placeholder bodies (invariant I4).
    /// An unparseable file locates nothing - inventing bodies from text
    /// `syn` refused would fabricate.
    fn locate_symbol_bodies(
        &self,
        source_text: &str,
        wanted: &[(String, ariadne_lang::SymbolKind)],
    ) -> Vec<SymbolBody> {
        let Ok(parsed) = syn::parse_file(source_text) else {
            return Vec::new();
        };
        wanted
            .iter()
            .filter_map(|(name, _kind)| {
                written_item_named(&parsed.items, name).map(|item| SymbolBody {
                    name: name.clone(),
                    body: item.to_token_stream().to_string(),
                })
            })
            .collect()
    }

    /// RISK-MODTREE (shape sec. 6): the extracted file must land beside its
    /// parent module file - where `mod <stem>;` can reach it - exactly like
    /// Scala's move semantics reject a staging dir the compiler never reads.
    fn places_generated_units_in_place(&self) -> bool {
        true
    }
}

/// One `use <dep>;\n` per required dep, sorted and deduped, plus the
/// trailing separator the caller folds in. The renderer is dumb by
/// contract (the Scala twin's LOCK): referenced-only selection lives
/// upstream in the `required_deps` the planner assembles; the deps are
/// Rust module paths (`use`-space), not file paths - a producer feeding
/// file paths is the D-M23-13 class and belongs to the R-9 hook, not to a
/// silent fix-up here.
fn render_use_block(deps: &[String]) -> String {
    let mut ordered: Vec<&String> = deps.iter().collect();
    ordered.sort_unstable();
    ordered.dedup();
    if ordered.is_empty() {
        return String::new();
    }
    let mut block = String::new();
    for dep in ordered {
        block.push_str("use ");
        block.push_str(dep);
        block.push_str(";\n");
    }
    block
}

/// The first top-level written item whose written name matches `name`, over
/// the analyzer's contract set (fn/struct/enum/trait/type/const/static/mod
/// plus the written `impl` form). The name table mirrors
/// `parser_items::item_written_name`, which is private to that module and
/// must stay there (touch-set law); a plugin never depends on another
/// language's plugin, so the discipline is mirrored, not imported.
fn written_item_named<'a>(items: &'a [syn::Item], name: &str) -> Option<&'a syn::Item> {
    items.iter().find(|item| written_item_name(item).as_deref() == Some(name))
}

fn written_item_name(item: &syn::Item) -> Option<String> {
    match item {
        syn::Item::Fn(item_fn) => Some(item_fn.sig.ident.to_string()),
        syn::Item::Struct(item_struct) => Some(item_struct.ident.to_string()),
        syn::Item::Enum(item_enum) => Some(item_enum.ident.to_string()),
        syn::Item::Trait(item_trait) => Some(item_trait.ident.to_string()),
        syn::Item::Type(item_type) => Some(item_type.ident.to_string()),
        syn::Item::Const(item_const) => Some(item_const.ident.to_string()),
        syn::Item::Static(item_static) => Some(item_static.ident.to_string()),
        syn::Item::Mod(item_mod) => Some(item_mod.ident.to_string()),
        syn::Item::Impl(item_impl) => impl_written_name(item_impl),
        _ => None,
    }
}

/// The written `impl` form (`impl <Type>` / `impl <Trait> for <Type>`), the
/// analyzer's nameable-only rule mirrored for the same contract set.
fn impl_written_name(item_impl: &syn::ItemImpl) -> Option<String> {
    let type_name = match &*item_impl.self_ty {
        syn::Type::Path(type_path) => type_path
            .path
            .segments
            .last()
            .map(|segment| segment.ident.to_string()),
        _ => None,
    }?;
    Some(match &item_impl.trait_ {
        Some((_not, trait_path, _for)) => {
            let trait_name = trait_path
                .segments
                .iter()
                .map(|segment| segment.ident.to_string())
                .collect::<Vec<String>>()
                .join("::");
            format!("impl {trait_name} for {type_name}")
        }
        None => format!("impl {type_name}"),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use ariadne_lang_api::types::SymbolKind;

    fn body(name: &str, text: &str) -> SymbolBody {
        SymbolBody {
            name: name.to_string(),
            body: text.to_string(),
        }
    }

    fn extract(bodies: &[SymbolBody], namespace: &str, deps: &[&str]) -> String {
        RustSourceExtractor
            .extract(
                bodies,
                namespace,
                &deps.iter().map(|dep| dep.to_string()).collect::<Vec<String>>(),
            )
            .content
    }

    /// The R-4 fixture shape (`tests/fixtures/rust-basic/src/models/user.rs`,
    /// cited read-only, brace-balanced single-line idiom of the analyzer's
    /// own test fixtures): a derive attribute, a struct, and a function.
    const WRITTEN_SOURCE: &str = "// nested module file\n#[derive(Debug)]\npub struct User { pub name: String }\n\npub fn default_user() -> User { User { name: String::new() } }\n";

    /// The R-4 macro caveat specimen shape (`src/macro_specimen.rs`): the
    /// generated module exists only after expansion; `written_code_only` is
    /// written code syn can see.
    const MACRO_SPECIMEN: &str = "macro_rules! declare_hidden_module { () => { mod generated_by_macro { pub fn invisible_without_expansion() -> u32 { 1 } } }; }\n\ndeclare_hidden_module!();\n\npub fn written_code_only() -> u32 { 2 }\n";

    #[test]
    fn extract_renders_header_use_block_and_item_text_byte_exact() {
        assert_eq!(
            extract(&[body("User", "pub struct User;")], "", &["crate::models::user"]),
            "// generated by AriadnesThread (rust-language R-8): extracted Rust unit\n\
             // syn-printed content - comments in the written source do not survive\n\n\
             use crate::models::user;\n\n\
             pub struct User;\n",
            "byte-locked shape: header, sorted `use` block, item text"
        );
    }

    #[test]
    fn empty_deps_omit_the_use_block_and_its_separator() {
        assert_eq!(
            extract(&[body("User", "pub struct User;")], "", &[]),
            "// generated by AriadnesThread (rust-language R-8): extracted Rust unit\n\
             // syn-printed content - comments in the written source do not survive\n\n\
             pub struct User;\n"
        );
    }

    #[test]
    fn deps_render_sorted_deduped_and_verbatim() {
        assert_eq!(
            extract(&[], "", &["crate::z", "crate::a", "crate::z"]),
            "// generated by AriadnesThread (rust-language R-8): extracted Rust unit\n\
             // syn-printed content - comments in the written source do not survive\n\n\
             use crate::a;\nuse crate::z;\n\n",
            "dumb-renderer discipline (Scala twin): selection is upstream"
        );
    }

    #[test]
    fn generated_source_reparses_with_syn_and_carries_the_item() {
        let content = extract(&[body("User", "pub struct User {\n    pub name: String,\n}")], "", &[]);
        let parsed = syn::parse_file(&content).expect("generated source re-parses");
        assert_eq!(
            parsed.items.len(),
            1,
            "the generated file carries the extracted item - the stub's \
             header-only bytes re-parse as ZERO items"
        );
    }

    #[test]
    fn every_generated_byte_is_ascii() {
        let content = extract(
            &[body("User", "pub struct User;")],
            "",
            &["crate::models::user"],
        );
        assert!(content.is_ascii(), "the ASCII rule covers generated bytes");
    }

    #[test]
    fn namespace_needs_no_clause_and_stays_empty_through_the_seam() {
        // Rust file reachability is placement in the module tree, not a
        // file-level namespace clause: the default `unit_namespace` (empty)
        // is the honest answer and the extract argument is clause-free.
        assert_eq!(RustSourceExtractor.unit_namespace(WRITTEN_SOURCE), "");
        assert!(!extract(&[body("U", "struct U;")], "crate::models", &[]).contains("crate::models"));
    }

    #[test]
    fn locate_symbol_bodies_prints_written_items_that_reparse() {
        let bodies =
            RustSourceExtractor.locate_symbol_bodies(WRITTEN_SOURCE, &[("User".to_string(), SymbolKind::Struct)]);
        assert_eq!(bodies.len(), 1, "the written struct is located");
        assert!(
            bodies[0].body.contains("struct User"),
            "the body carries the item text, not a placeholder"
        );
        syn::parse_str::<syn::Item>(&bodies[0].body).expect("located body re-parses as an item");
        assert!(
            !bodies[0].body.contains("nested module file"),
            "syn printing normalizes text (and drops comments - the D-2-class \
             honest limit, documented in the header)"
        );
    }

    #[test]
    fn locate_omits_names_that_are_not_written_in_the_file() {
        let bodies =
            RustSourceExtractor.locate_symbol_bodies(WRITTEN_SOURCE, &[("Ghost".to_string(), SymbolKind::Struct)]);
        assert!(bodies.is_empty(), "I4: an unlocatable name is omitted; the \
             engine keeps its placeholder body"
        );
    }

    #[test]
    fn locate_of_the_macro_specimen_yields_written_items_only() {
        let located = RustSourceExtractor.locate_symbol_bodies(
            MACRO_SPECIMEN,
            &[
                ("written_code_only".to_string(), SymbolKind::Function),
                ("generated_by_macro".to_string(), SymbolKind::Module),
            ],
        );
        let names: Vec<String> = located.iter().map(|found| found.name.clone()).collect();
        assert_eq!(
            names,
            vec!["written_code_only".to_string()],
            "D-2: extraction sees WRITTEN items only - the macro-generated \
             module is not written code and never fabricates a body"
        );
    }

    #[test]
    fn generated_units_place_in_place_for_the_mod_tree() {
        assert!(
            RustSourceExtractor.places_generated_units_in_place(),
            "RISK-MODTREE: a staging dir the module tree never reads strands \
             the extracted file - in-place like Scala's move semantics"
        );
    }

    #[test]
    fn path_is_left_to_the_engine_like_cpp_and_scala() {
        let generated = RustSourceExtractor.extract(&[], "", &[]);
        assert_eq!(generated.path, PathBuf::new());
    }

    #[test]
    fn extractor_emits_real_rust_bytes_not_the_deferral_stub() {
        let content = extract(&[body("User", "pub struct User;")], "", &["crate::models::user"]);
        assert!(
            !content.contains("not wired yet"),
            "the R-3 deferral stub is retired at R-8 (Scala's \
             plugin_extractor_emits_real_scala_bytes_not_the_stub idiom)"
        );
    }
}
