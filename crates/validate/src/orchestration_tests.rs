#[test]
fn collect_move_removals_keeps_multiple_units_per_file() {
    // The unit is the atomic move region (T8b): two moved units whose
    // rewrites share one old dep yield one offer PER unit, not one merge.
    let dir = tempfile::tempdir().unwrap();
    fs::write(dir.path().join("legacy.h"), "// aggregation\n").unwrap();

    let removals = collect_move_removals(
        dir.path(),
        &migration_of(vec![rewrite("src/m.cpp", &["legacy.h"], &["x.h", "y.h"])]),
        &extraction_of(vec![
            unit_named("x.h", &["Alpha"]),
            unit_named("y.h", &["Beta"]),
        ]),
    );

    assert_eq!(
        removals,
        BTreeSet::from([
            (PathBuf::from("legacy.h"), vec!["Alpha".to_string()]),
            (PathBuf::from("legacy.h"), vec!["Beta".to_string()]),
        ])
    );
}

// ── UTA-T4 item 6: rolled-back error decoration + verify_restored ──────────

#[test]
fn rolled_back_error_carries_original_cause_when_rollback_fails() {
    // Two units: the first writes generated/outer.h/inner.h, which makes
    // generated/outer.h a DIRECTORY; the second wants generated/outer.h
    // itself. Writing onto a directory always fails, and the rollback then
    // chokes removing that directory through plain remove_file - both
    // failures are deterministic on Windows and Unix.
    let dir = tempfile::tempdir().unwrap();
    let repo = dir.path();

    let extraction = ExtractionResult {
        plan_id: "P-ROLL".into(),
        headers: vec![unit_named("outer.h/inner.h", &[]), unit_named("outer.h", &[])],
        errors: vec![],
    };
    let migration = migration_of(vec![]);

    let outcome = TransactionApplier::apply_with(
        repo,
        &extraction,
        &migration,
        &NoTextMutationRewriter,
        &RecordingDelegatingExtractor::default(),
    );

    let err = match outcome {
        Ok(_) => panic!("writing generated/outer.h over a directory must fail"),
        Err(err) => err,
    };
    let chain = format!("{err:#}");
    assert!(
        chain.contains("rollback incomplete after"),
        "the failing rollback must be reported as incomplete, not success: {chain}"
    );
    assert!(
        !chain.contains("rolled back"),
        "a failed rollback must never claim the clean 'rolled back N files' decoration: {chain}"
    );
    // The original cause rides inside the marker's own text: the segment
    // after "after: " is the cause Display and must not be empty.
    let cause_segment = chain
        .splitn(2, "rollback incomplete after: ")
        .nth(1)
        .unwrap_or("");
    assert!(
        !cause_segment.is_empty(),
        "the original write failure must be carried in the error: {chain}"
    );
    // Honest half-restoration: the rollback ran (the written file is gone)
    // and stopped at the directory it cannot remove (an unrestored tree is
    // never reported as rolled back).
    assert!(!repo.join("generated/outer.h/inner.h").exists());
    assert!(repo.join("generated/outer.h").is_dir());
}

#[test]
fn rolled_back_error_counts_processed_paths_when_rollback_succeeds() {
    // Companion pin: when the rollback itself succeeds, the ORIGINAL cause
    // is the reported error decorated with the processed-path count
    // (snapshot entries + created paths). A plain file blocking a nested
    // unit's parent dir fails the batch after one unit wrote cleanly.
    let dir = tempfile::tempdir().unwrap();
    let repo = dir.path();
    fs::create_dir_all(repo.join("generated")).unwrap();
    fs::write(repo.join("generated/b.h"), "// occupies the parent slot\n").unwrap();

    let extraction = ExtractionResult {
        plan_id: "P-ROLL2".into(),
        headers: vec![unit_named("a.h", &[]), unit_named("b.h/deep.h", &[])],
        errors: vec![],
    };
    let migration = migration_of(vec![]);

    let outcome = TransactionApplier::apply_with(
        repo,
        &extraction,
        &migration,
        &NoTextMutationRewriter,
        &RecordingDelegatingExtractor::default(),
    );

    let err = match outcome {
        Ok(_) => panic!("a file occupying a unit's parent dir must fail the batch"),
        Err(err) => err,
    };
    // Count note: validate creates each unit's parent dir BEFORE pushing
    // the path to new_paths, so the blocked second unit is never counted -
    // processed = 2 snapshot entries + 1 created path.
    assert!(
        err.to_string().contains("rolled back 3 files"),
        "2 snapshot entries + 1 created path must be counted: {err:#}"
    );
    assert!(
        !repo.join("generated/a.h").exists(),
        "the clean rollback must have removed the successfully written unit"
    );
    assert!(repo.join("generated/b.h").is_file(), "pre-existing bytes stay");
}

#[test]
fn verify_restored_reports_state_mismatch_on_external_mutation() {
    let dir = tempfile::tempdir().unwrap();
    let repo = dir.path();
    let src_dir = repo.join("src");
    fs::create_dir_all(&src_dir).unwrap();
    fs::write(src_dir.join("main.cpp"), consumer_source("old.h")).unwrap();

    let extraction = ExtractionResult {
        plan_id: "P-VERIFY".into(),
        headers: vec![unit_named("new.h", &[])],
        errors: vec![],
    };
    let migration = migration_of(vec![rewrite("src/main.cpp", &["old.h"], &["new.h"])]);

    let (snap, new_paths) = TransactionApplier::apply_with(
        repo,
        &extraction,
        &migration,
        &NoTextMutationRewriter,
        &RecordingDelegatingExtractor::default(),
    )
    .unwrap();
    // verify_restored judges the tree against the pre-apply snapshot, so
    // it only reaches Ok after the rollback removed the created unit.
    TransactionApplier::rollback(&snap, &new_paths).unwrap();
    assert!(TransactionApplier::verify_restored(&snap).is_ok());

    // Mutate a snapshotted path from OUTSIDE the transaction: the
    // fingerprint must catch it.
    fs::write(src_dir.join("main.cpp"), "tampered after snapshot").unwrap();
    assert_eq!(
        TransactionApplier::verify_restored(&snap),
        Err("State mismatch".to_string())
    );
}
