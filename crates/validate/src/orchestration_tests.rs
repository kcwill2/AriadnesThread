#[test]
fn apply_with_orchestrates_snapshot_write_and_rollback_only() {
    // Retarget of the retired 3-arg shim test (M23 T2): `apply_with`
    // still only orchestrates — the neutral rewriter leaves consumer
    // text untouched, the extractor owns the generated text, and
    // rollback restores everything.
    let dir = tempfile::tempdir().unwrap();
    let repo = dir.path();

    let src_dir = repo.join("src");
    fs::create_dir_all(&src_dir).unwrap();
    let consumer = src_dir.join("main.cpp");
    fs::write(&consumer, consumer_source("old.h")).unwrap();

    let extraction = ExtractionResult {
        plan_id: "P1".into(),
        headers: vec![GeneratedUnit {
            path: "new.h".into(),
            symbols: vec![],
            required_deps: vec![],
            primary_source_text: None,
        }],
        errors: vec![],
    };

    let migration = MigrationPreview {
        plan_id: "P1".into(),
        rewrites: vec![ConsumerRewrite {
            consumer_file: PathBuf::from("src/main.cpp"),
            old_includes: vec![PathBuf::from("old.h")],
            new_includes: vec![PathBuf::from("new.h")],
            side_effect_preservations: vec![],
        }],
    };

    let (snap, new_paths) = TransactionApplier::apply_with(
        repo,
        &extraction,
        &migration,
        &NoTextMutationRewriter,
        &RecordingDelegatingExtractor::default(),
    )
    .unwrap();

    // Created + rolled back, but consumer text untouched and the
    // generated file is exactly the extractor's rendering.
    assert_eq!(
        fs::read_to_string(&consumer).unwrap(),
        consumer_source("old.h")
    );
    assert_eq!(
        fs::read_to_string(repo.join("generated/new.h")).unwrap(),
        "FAKE-UNIT ns=\n"
    );

    TransactionApplier::rollback(&snap, &new_paths).unwrap();
    assert!(TransactionApplier::verify_restored(&snap).is_ok());
    assert!(!repo.join("generated/new.h").exists());
}

// ── UTA-T4 item 5: collect_move_removals guard table ───────────────────────

fn unit_named(path: &str, symbol_names: &[&str]) -> GeneratedUnit {
    GeneratedUnit {
        path: PathBuf::from(path),
        symbols: symbol_names
            .iter()
            .map(|name| ExtractedSymbol {
                name: name.to_string(),
                qualified_id: name.to_string(),
                kind: SymbolKind::Class,
                body: format!("// Symbol: {name} (Class)"),
            })
            .collect(),
        required_deps: vec![],
        primary_source_text: None,
    }
}

fn rewrite(
    consumer: &str,
    old_includes: &[&str],
    new_includes: &[&str],
) -> ConsumerRewrite {
    ConsumerRewrite {
        consumer_file: PathBuf::from(consumer),
        old_includes: old_includes.iter().map(PathBuf::from).collect(),
        new_includes: new_includes.iter().map(PathBuf::from).collect(),
        side_effect_preservations: vec![],
    }
}

fn migration_of(rewrites: Vec<ConsumerRewrite>) -> MigrationPreview {
    MigrationPreview {
        plan_id: "P-GUARD".into(),
        rewrites,
    }
}

fn extraction_of(units: Vec<GeneratedUnit>) -> ExtractionResult {
    ExtractionResult {
        plan_id: "P-GUARD".into(),
        headers: units,
        errors: vec![],
    }
}

/// The one happy-path row the guards are carved out of: an on-disk old
/// dependency plus a matching generated unit yields the move offer.
#[test]
fn collect_move_removals_offers_plain_move() {
    let dir = tempfile::tempdir().unwrap();
    fs::write(dir.path().join("legacy.h"), "// aggregation\n").unwrap();

    let removals = collect_move_removals(
        dir.path(),
        &migration_of(vec![rewrite("src/m.cpp", &["legacy.h"], &["g.h"])]),
        &extraction_of(vec![unit_named("g.h", &["Widget"])]),
    );

    assert_eq!(
        removals,
        BTreeSet::from([(PathBuf::from("legacy.h"), vec!["Widget".to_string()])])
    );
}

