const FIXTURE: &str = "scala-basic";

/// The five `src/main/scala` sources the shaper must turn into units.
const MAIN_SCALA_SOURCES: [&str; 5] = [
    "src/main/scala/com/example/Main.scala",
    "src/main/scala/com/example/models/Order.scala",
    "src/main/scala/com/example/models/User.scala",
    "src/main/scala/com/example/models/all.scala",
    "src/main/scala/com/example/services/OrderService.scala",
];

/// The sixth recorded `.scala`: the test-root spec (recorded by discovery,
/// excluded by the shaper - `src/test/scala` is the exclusion tag).
const TEST_ROOT_SPEC: &str = "src/test/scala/com/example/OrderServiceSpec.scala";

struct IsolatedScalaRepo {
    _temp: tempfile::TempDir,
    root: PathBuf,
}

fn fixture_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("fixtures")
        .join(name)
}

/// Throwaway copy of the fixture (self-contained per the M18 stall lessons -
/// the frozen m18 harness is never reused, so it stays byte-identical).
fn isolated_scala_repo(label: &str) -> Result<IsolatedScalaRepo> {
    let temp = tempfile::tempdir()?;
    let root = temp.path().join(label);
    copy_tree(&fixture_path(FIXTURE), &root)?;
    Ok(IsolatedScalaRepo { _temp: temp, root })
}

fn copy_tree(src: &Path, dst: &Path) -> Result<()> {
    fs::create_dir_all(dst)?;
    for entry in fs::read_dir(src)? {
        let entry = entry?;
        let target = dst.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_tree(&entry.path(), &target)?;
        } else {
            fs::copy(entry.path(), &target)?;
        }
    }
    Ok(())
}

fn normalized_rel(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

fn discovered_rel_paths(root: &Path) -> Result<Vec<String>> {
    let repository = Repository::locate(root)?;
    let mut paths: Vec<String> = repository
        .discover()?
        .files
        .iter()
        .map(|record| normalized_rel(&record.path))
        .collect();
    paths.sort();
    Ok(paths)
}

fn sorted_file_ids(paths: &[&str]) -> Vec<u64> {
    let mut ids: Vec<u64> = paths
        .iter()
        .map(|path| FileId::from_relative_path(path).0)
        .collect();
    ids.sort();
    ids
}

#[test]
fn discover_lists_scala_sources() -> Result<()> {
    let repo_copy = isolated_scala_repo("discover")?;
    let repository = Repository::locate(&repo_copy.root)?;
    let discovery = repository.discover()?;

    let mut actual: Vec<String> = discovery
        .files
        .iter()
        .map(|record| normalized_rel(&record.path))
        .collect();
    actual.sort();
    let mut expected: Vec<String> = MAIN_SCALA_SOURCES
        .iter()
        .map(|path| path.to_string())
        .collect();
    expected.push(TEST_ROOT_SPEC.to_string());
    expected.sort();
    assert_eq!(actual, expected, "exactly the six .scala files are recorded");

    for record in &discovery.files {
        assert_eq!(record.kind, FileKind::ScalaSource);
        assert_eq!(record.language, SourceLanguage::Scala);
        assert_eq!(record.ownership, FileOwnership::Repository);
        assert_eq!(record.optimization_policy, OptimizationPolicy::Optimizable);
    }
    Ok(())
}

/// Kickoff-wording deviation, accepted (T-B ruling 4): shipped `policy.rs`
/// has NO `lib` rule and repo discovery traversal SKIPS `target/` dirs, so
/// "lib/+target/ -> ThirdParty/Generated via policy.rs" cannot mean
/// discovery classification. This test locks the REAL boundary behavior
/// (no records under either dir; policy still says Generated/Frozen for the
/// target path) plus the M20 marker lock on the plugin modeling.
#[test]
fn external_frozen_boundary_lock() -> Result<()> {
    let repo_copy = isolated_scala_repo("boundary")?;
    let generated = repo_copy
        .root
        .join("target")
        .join("scala-2.13")
        .join("classes")
        .join("Generated.scala");
    fs::create_dir_all(generated.parent().unwrap())?;
    fs::write(&generated, "// generated by a hypothetical sbt run\n")?;

    let paths = discovered_rel_paths(&repo_copy.root)?;
    assert!(
        paths.iter().all(|path| !path.starts_with("target/")),
        "traversal skips target/ (real boundary behavior): {paths:?}"
    );
    assert!(
        paths.iter().all(|path| !path.starts_with("lib/")),
        "lib/legacy.jar is FileKind::Other, never recorded: {paths:?}"
    );

    let (ownership, policy) = classify_ownership_and_policy(
        Path::new("target/scala-2.13/classes/Generated.scala"),
        false,
    );
    assert_eq!(ownership, FileOwnership::Generated);
    assert_eq!(policy, OptimizationPolicy::Frozen);

    let markers = ScalaPlugin::new().modeling().external_path_markers;
    assert!(
        markers.iter().any(|marker| marker == "lib"),
        "M20 enforcement lock: lib is an external marker: {markers:?}"
    );
    assert!(
        markers.iter().any(|marker| marker == "target"),
        "M20 enforcement lock: target is an external marker: {markers:?}"
    );
    Ok(())
}

#[test]
fn shaper_yields_scalac_units() -> Result<()> {
    let repo_copy = isolated_scala_repo("shaper")?;
    let repository = Repository::locate(&repo_copy.root)?;
    let discovery = repository.discover()?;
    let build = BuildDiscoverer::new(&repository.root)
        .with_repo_discovery(&discovery)
        .with_unit_shaper(Some(&ScalaUnitShaper))
        .discover()?;

    assert_eq!(build.contexts.len(), 1, "one sbt root-project context");
    let context = &build.contexts[0];
    assert_eq!(context.name, "root", "nearest *.sbt ancestor is the root");
    assert_eq!(context.compiler, "scalac");
    assert_eq!(context.language, SourceLanguage::Scala);

    assert_eq!(
        build.translation_units.len(),
        MAIN_SCALA_SOURCES.len(),
        "one unit per src/main/scala file (test root excluded)"
    );
    let mut unit_ids: Vec<u64> = build
        .translation_units
        .iter()
        .map(|unit| unit.file_id.0)
        .collect();
    unit_ids.sort();
    assert_eq!(unit_ids, sorted_file_ids(&MAIN_SCALA_SOURCES));
    for unit in &build.translation_units {
        assert_eq!(unit.language, SourceLanguage::Scala);
    }

    let cpp_flavored = build
        .contexts
        .iter()
        .any(|ctx| ctx.compiler == "cl.exe" || ctx.language == SourceLanguage::Cpp);
    assert!(
        !cpp_flavored,
        "the compile_commands path is not entered (D8 lock, no C++ diagnostics)"
    );
    Ok(())
}

#[test]
fn plugin_contract_in_default_registry() {
    let registry = ariadne_cli::registry::default_registry();
    assert_eq!(
        registry.languages(),
        vec![SourceLanguage::Cpp, SourceLanguage::Scala]
    );

    let scala = registry
        .plugin_for_id(SourceLanguage::Scala)
        .expect("Scala registered in the CLI default registry (D9)");
    assert_eq!(
        scala.capabilities(),
        LanguageCapabilities {
            discovery: true,
            dependency_graph: true,
            semantic_index: true,
            load_metric: true,
            planning: true,
            extraction: true,
            rewriting: true,
            validation: true,
            requires_toolchain: false,
        },
        "EVOLVED at M23 T7 (D-M23-6 flip): the pre-flip form of this lock was \
         the plan:381 capability-literal blocker (four false bits); the flip \
         turned them on, requires_toolchain stays false (A3/I7). The \
         per-language stage routing this enables is locked cli-side \
         (registry.rs capability_backend_resolves_*). \
         Same byte-exact literal discipline, new authority."
    );

    assert_eq!(
        registry.detect_language(Path::new("src/main/scala/com/example/Main.scala")),
        Some(SourceLanguage::Scala)
    );
    assert_eq!(
        registry.detect_language(Path::new("src/main.cpp")),
        Some(SourceLanguage::Cpp)
    );

    assert_eq!(
        registry
            .unit_shaper_for()
            .expect("the default registry selects a unit shaper")
            .build_markers(),
        vec!["CMakeLists.txt", "compile_commands.json", ".vcxproj"],
        "registration-order lock: the C++ shaper still wins first-wins"
    );
}

