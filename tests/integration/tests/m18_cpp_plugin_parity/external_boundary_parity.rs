fn directive_capture_parity() -> Result<()> {
    let repo = isolated_repo(FIXTURE, "eb-resolver")?;
    let (discovery, _build) = repo_inputs(&repo.root)?;
    let resolver = CppDependencyResolver::new();
    let ctx = ResolutionContext {
        repo_root: repo.root.as_path(),
        search_paths: Vec::new(),
    };
    let mut checked = 0usize;
    for record in analyzable_records(&discovery) {
        let rel = normalized_rel(&record.path);
        let content = fs::read_to_string(record.canonical_path.clone())?;
        let wanted: Vec<&(&str, &str, bool, u32, u32)> =
            EXT_BOUNDARY_DIRECTIVES
                .iter()
                .filter(|entry| lockable(entry.0) == rel)
                .collect();

        // Oracle self-lock: the relocated legacy parser must still produce the
        // vendored capture (a parser change trips here, not on the plugin).
        let parsed = parse_include_directives(&content);
        assert_eq!(parsed.len(), wanted.len(), "{rel}: directive count drifted");
        for (directive, entry) in parsed.iter().zip(&wanted) {
            let &(want_rel, want_raw, want_angled, want_line, want_column) = *entry;
            assert_eq!(lockable(want_rel), rel, "capture rows must be grouped by file");
            assert_eq!(directive.raw_path, want_raw, "{rel}");
            assert_eq!(directive.is_angled, want_angled, "{rel}:{want_raw}");
            assert_eq!(directive.line, want_line, "{rel}:{want_raw}");
            assert_eq!(directive.column, want_column, "{rel}:{want_raw}");
        }

        // The plugin surface must reproduce the vendored capture exactly.
        let edges = resolver.resolve_edges(record.id, &record.path, &content, &ctx);
        assert_eq!(edges.len(), wanted.len(), "{rel}: resolve_edges drifted");
        for (edge, entry) in edges.iter().zip(&wanted) {
            let &(want_rel, want_raw, want_angled, want_line, want_column) = *entry;
            assert_eq!(lockable(want_rel), rel, "capture rows must be grouped by file");
            assert_eq!(edge.source_file, record.id, "{rel}");
            assert_eq!(edge.source_rel_path, record.path, "{rel}");
            assert_eq!(edge.raw_target, want_raw, "{rel}");
            assert!(!edge.is_wildcard, "C++ has no wildcard directives");
            assert_eq!(
                matches!(edge.style, DirectiveStyle::Angled),
                want_angled,
                "{rel}:{}",
                edge.raw_target
            );
            assert_eq!(edge.line, want_line, "{rel}:{}", edge.raw_target);
            assert_eq!(edge.column, want_column, "{rel}:{}", edge.raw_target);
        }
        checked += edges.len();
    }
    assert!(checked >= 4, "fixture directives were checked: {checked}");
    Ok(())
}

fn closure_parity() -> Result<()> {
    let repo = isolated_repo(FIXTURE, "eb-closure")?;
    let (discovery, build) = repo_inputs(&repo.root)?;
    assert_eq!(
        build.translation_units.len(),
        1,
        "fixture must shape exactly one TU from compile_commands.json"
    );
    let tu = &build.translation_units[0];
    let vendored = vendored_legacy_closure(tu, &repo.root, &discovery, &build.contexts);
    let plugin = plugin_driven_closure(tu, &repo.root, &discovery, &build.contexts)?;

    // AUTHORITY CHECK first: production must reproduce the legacy oracle. On
    // disagreement this names both sides — never bend the capture to match
    // production (module docs, authority rule).
    let describe = |files: &[(u64, String)]| {
        files
            .iter()
            .map(|(id, path)| format!("{id}:{path}"))
            .collect::<Vec<_>>()
            .join(" | ")
    };
    assert_eq!(
        vendored,
        plugin,
        "{}: closure ORDER/membership diverged\n  legacy oracle: {}\n  production:    {}",
        normalized_rel(&tu.source_path),
        describe(&vendored),
        describe(&plugin)
    );

    // Permanent end-to-end lock: membership+order equal to the vendored
    // legacy capture (path form; ids are locked by the oracle comparison and
    // the outcome table above), and the divergence-(i) subjects are present.
    let tu_rel = normalized_rel(&tu.source_path);
    let closure_paths: Vec<String> = vendored.iter().map(|(_, path)| path.clone()).collect();
    let expected = EXT_BOUNDARY_CLOSURES
        .iter()
        .find(|(captured_tu, _)| lockable(captured_tu) == tu_rel)
        .map(|(_, members)| members.iter().map(|m| lockable(m)).collect::<Vec<_>>())
        .unwrap_or_else(|| panic!("no vendored closure capture for TU {tu_rel}"));
    assert_eq!(
        expected, closure_paths,
        "{tu_rel}: closure drifted from the vendored legacy capture"
    );
    assert!(
        closure_paths.contains(&"third_party/external_lib/api.h".to_string()),
        "divergence-(i): ThirdParty header reached only via -I must stay in the closure"
    );
    assert!(
        closure_paths.contains(&"third_party/external_lib/api_impl.h".to_string()),
        "divergence-(i): scanning must continue THROUGH External-classified headers"
    );
    Ok(())
}

fn outcome_table_parity() -> Result<()> {
    let repo = isolated_repo(FIXTURE, "eb-outcomes")?;
    let (discovery, build) = repo_inputs(&repo.root)?;
    let context = build
        .contexts
        .first()
        .cloned()
        .unwrap_or_else(|| CompilationContext::new("parity", "clang++"));
    let search_paths: Vec<std::path::PathBuf> = context
        .include_dirs
        .iter()
        .chain(context.system_include_dirs.iter())
        .cloned()
        .collect();
    let ctx = ResolutionContext {
        repo_root: repo.root.as_path(),
        search_paths,
    };
    let catalog = FileCatalog::from_records(&discovery.files);
    let legacy = ariadne_lang_cpp::IncludeResolver::new(&repo.root)
        .with_repo_discovery(&discovery)
        .with_context(&context);
    let plugin = CppDependencyResolver::new();

    let mut checked = 0usize;
    let mut destinations = 0usize;
    for record in analyzable_records(&discovery) {
        let content = fs::read_to_string(record.canonical_path.clone())?;
        for directive in parse_include_directives(&content) {
            let legacy_edge = legacy.resolve_directive(record.id, &record.path, &directive);
            let edge = RawDepEdge {
                source_file: record.id,
                source_rel_path: record.path.clone(),
                raw_target: directive.raw_path.clone(),
                is_wildcard: false,
                style: if directive.is_angled {
                    DirectiveStyle::Angled
                } else {
                    DirectiveStyle::Quoted
                },
                line: directive.line,
                column: directive.column,
            };
            let outcome = match plugin.resolve_target(&edge, &catalog, &ctx) {
                ResolveOutcome::Resolved(id) => Some(id),
                ResolveOutcome::Wildcard(_) => {
                    panic!("C++ resolvers never emit wildcard outcomes")
                }
                // The documented parity table: catalog misses run the legacy
                // on-disk candidate fallback shared with the permanent walks.
                ResolveOutcome::External | ResolveOutcome::Unresolved => {
                    ariadne_lang::first_ondisk_include_candidate(
                        &edge.raw_target,
                        edge.style,
                        &edge.source_rel_path,
                        &ctx.search_paths,
                        &repo.root,
                        &|path: &Path| path.exists(),
                    )
                    .map(|(id, _)| id)
                }
            };
            assert_eq!(
                legacy_edge.destination, outcome,
                "{}:{} directive {:?} outcome table diverged",
                normalized_rel(&record.path),
                directive.line,
                directive.raw_path
            );
            checked += 1;
            destinations += usize::from(outcome.is_some());
        }
    }
    assert!(checked >= 4, "fixture directives were checked: {checked}");
    // The exists-nowhere angled include is captured as legacy left it: NO
    // destination (unresolved edge), so the destination count must be below
    // the directive count.
    assert!(
        destinations < checked,
        "the exists-nowhere angled include must stay destination-less, as legacy produced"
    );
    Ok(())
}

fn graph_edge_classification() -> Result<()> {
    let repo = isolated_repo(FIXTURE, "eb-graph")?;
    let (discovery, _build) = repo_inputs(&repo.root)?;
    let registry = ariadne_cli::registry::default_registry();
    let graph = ariadne_graph::build_dependency_graph(&repo.root, &registry)?;

    let id_of = |rel: &str| {
        FileCatalog::from_records(&discovery.files)
            .by_rel_path(rel)
            .unwrap_or_else(|| panic!("fixture file {rel} missing from discovery"))
    };
    let edge_from = |source_rel: &str, raw: &str| {
        let source = id_of(source_rel);
        graph
            .edges
            .iter()
            .find(|edge| edge.source == source && edge.raw_path == raw)
            .unwrap_or_else(|| panic!("no graph edge {source_rel} -> {raw}"))
    };

    // ThirdParty target reached only via `-I third_party`: the edge KEEPS its
    // destination and travels with kind External (divergence-(i) on the
    // graph side — kind is an edge property, not an outcome that hides it).
    let api = edge_from("src/main.cpp", "external_lib/api.h");
    assert_eq!(api.destination, Some(id_of("third_party/external_lib/api.h")));
    assert_eq!(api.kind, IncludeKind::External, "ThirdParty target → External edge");
    assert_eq!(api.language, SourceLanguage::Cpp);

    // Scanning continues THROUGH the External edge: its quoted child is an
    // edge too, also External by target ownership.
    let api_impl = edge_from("third_party/external_lib/api.h", "api_impl.h");
    assert_eq!(api_impl.destination, Some(id_of("third_party/external_lib/api_impl.h")));
    assert_eq!(api_impl.kind, IncludeKind::External);

    // Non-ThirdParty search-path header: destination kept, kind Local.
    let sdk = edge_from("src/main.cpp", "sdk_bridge.h");
    assert_eq!(sdk.destination, Some(id_of("ext_sdk/sdk_bridge.h")));
    assert_eq!(sdk.kind, IncludeKind::Local);

    // The exists-nowhere angled include keeps the legacy unresolved shape:
    // no destination, System kind from the angled spelling.
    let missing = edge_from("src/main.cpp", "missing_global.h");
    assert_eq!(missing.destination, None);
    assert_eq!(missing.kind, IncludeKind::System);

    // Plain quoted include unaffected by the reconciliation.
    let core = edge_from("src/main.cpp", "core.h");
    assert_eq!(core.destination, Some(id_of("src/core.h")));
    assert_eq!(core.kind, IncludeKind::Local);
    Ok(())
}

fn capture_self_check() -> Result<()> {
    let repo = isolated_repo(FIXTURE, "eb-capture")?;
    let (discovery, build) = repo_inputs(&repo.root)?;
    for record in analyzable_records(&discovery) {
        let content = fs::read_to_string(record.canonical_path.clone())?;
        for directive in parse_include_directives(&content) {
            println!(
                "@@EBDIR\t{}\t{}\t{}\t{}\t{}\t{}",
                FIXTURE,
                serde_json::to_string(&normalized_rel(&record.path))?,
                serde_json::to_string(&directive.raw_path)?,
                directive.is_angled,
                directive.line,
                directive.column
            );
        }
    }
    // Closure capture rows come ONLY from the vendored legacy oracle walk —
    // never from the plugin path (authority rule, module docs).
    for tu in &build.translation_units {
        let files = vendored_legacy_closure(tu, &repo.root, &discovery, &build.contexts);
        println!(
            "@@EBCLOSURE\t{}\t{}\t{}",
            FIXTURE,
            serde_json::to_string(&normalized_rel(&tu.source_path))?,
            serde_json::to_string(&files.iter().map(|(_, p)| normalized_rel(Path::new(p))).collect::<Vec<_>>())?
        );
    }
    Ok(())
}

const FIXTURE: &str = "m18-external-boundary";

/// Vendored verbatim from `resolver_parity::vendored_legacy_closure` (which is
/// itself vendored from `git show ceac55f:crates/scheduler/src/tu_store.rs`'s
/// `compute_tu_closure` walk): the legacy LIFO edge-stack include closure
/// through the relocated pre-M18 `IncludeResolver`, with the compilation
/// context's search paths fed exactly as the legacy context binding did.
fn vendored_legacy_closure(
    tu: &TranslationUnit,
    repo_root: &Path,
    discovery: &RepositoryDiscoveryResult,
    contexts: &[CompilationContext],
) -> Vec<(u64, String)> {
    let context = contexts
        .iter()
        .find(|candidate| candidate.name == tu.context_name)
        .cloned()
        .unwrap_or_else(|| CompilationContext::new(&tu.context_name, "clang++"));
    let path_by_id: HashMap<FileId, std::path::PathBuf> = discovery
        .files
        .iter()
        .map(|record| (record.id, record.path.clone()))
        .collect();
    let resolver = ariadne_lang_cpp::IncludeResolver::new(repo_root)
        .with_repo_discovery(discovery)
        .with_context(&context);

    let source_abs = repo_root.join(&tu.source_path);
    let source_content = fs::read_to_string(&source_abs).unwrap_or_default();
    let edges = resolver.resolve_file_includes(tu.file_id, &tu.source_path, &source_content);

    let mut files = vec![(tu.file_id, tu.source_path.clone())];
    let mut visited: HashSet<FileId> = HashSet::new();
    visited.insert(tu.file_id);

    let mut queue = edges;
    while let Some(edge) = queue.pop() {
        if let Some(dest_id) = edge.destination {
            if visited.insert(dest_id) {
                let dest_path = path_by_id
                    .get(&dest_id)
                    .cloned()
                    .or_else(|| edge.resolved_path.clone());
                let Some(dest_path) = dest_path else { continue };
                let header_abs = repo_root.join(&dest_path);
                if let Ok(header_content) = fs::read_to_string(&header_abs) {
                    files.push((dest_id, dest_path.clone()));
                    queue.extend(resolver.resolve_file_includes(
                        dest_id,
                        &dest_path,
                        &header_content,
                    ));
                }
            }
        }
    }

    files
        .into_iter()
        .map(|(id, path)| (id.0, normalized_rel(&path)))
        .collect()
}

/// The same closure computed through the permanent registry path
/// (`scheduler::compute_tu_closure_plugin` driven by `CppDependencyResolver`).
fn plugin_driven_closure(
    tu: &TranslationUnit,
    repo_root: &Path,
    discovery: &RepositoryDiscoveryResult,
    contexts: &[CompilationContext],
) -> Result<Vec<(u64, String)>> {
    let store_ctx = ariadne_scheduler::TuStoreContext::new(discovery, contexts.to_vec());
    let resolver = CppDependencyResolver::new();
    let closure = ariadne_scheduler::compute_tu_closure_plugin(
        tu,
        repo_root,
        &store_ctx,
        CURRENT_ANALYSIS_VERSION,
        &resolver,
        SourceLanguage::Cpp,
        CPP_ANALYSIS_FINGERPRINT,
    )?;
    Ok(closure
        .files
        .into_iter()
        .map(|(id, path, _content)| (id.0, normalized_rel(&path)))
        .collect())
}
