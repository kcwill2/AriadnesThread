//! Section 5 — external/third-party boundary parity (post-M18-audit finding 2).
//!
//! The M18.5 divergence-(i) reconciliation — ThirdParty/External-resolved
//! headers staying in TU closures via `ResolutionContext::search_paths` plus
//! the shared on-disk fallback (`scheduler::tu_store::edge_destinations`,
//! mirrored by `graph::builder`) — was previously locked only by unit tests of
//! the fallback mechanism. This section locks it END-TO-END on the
//! `m18-external-boundary` fixture, which has no analogue elsewhere: a
//! `third_party/`-owned header reached by an angled include through `-I`, an
//! out-of-`include/` header reached the same way, and an angled include that
//! exists nowhere.
//!
//! Authority rule honored here: every vendored capture below was generated
//! ONLY from the legacy oracle — the pre-M18 resolver relocated verbatim into
//! `ariadne_lang_cpp::IncludeResolver` (`git show e8422ef^:crates/graph/src/
//! resolver.rs`'s `collect_include_candidates` + discovery loop + ThirdParty→
//! External classification + on-disk fallback; `resolve_directive` is
//! byte-equivalent modulo the additive `language` field, verified against that
//! commit) driven through the vendored LIFO closure walk copied verbatim from
//! `resolver_parity` (itself vendored from `git show ceac55f:crates/scheduler/
//! src/tu_store.rs::compute_tu_closure`). The `zz_capture_external_boundary`
//! test regenerates the captures from that oracle; production output is NEVER
//! an oracle here. If production and this oracle ever disagree, the closure
//! and outcome-table tests fail — the fix is to production, not to the capture.

